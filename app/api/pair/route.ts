import { NextResponse } from "next/server";
import crypto from "crypto";
import { createAdminClient } from "@/lib/supabase/admin";

export const runtime = "nodejs";

function newToken(): string {
  return crypto.randomBytes(24).toString("hex");
}
function hashToken(t: string): string {
  return crypto.createHash("sha256").update(t).digest("hex");
}

/**
 * POST /api/pair
 *
 * Pairs a phone with this company's server and issues a device token.
 *   - passenger: { kind: "passenger" }  → lightweight device, no code needed
 *   - driver:    { kind: "driver", pairing_token: "<code>" } → validates a
 *                one-time pairing code generated by the dashboard
 *
 * Response: { token, company, taxi?, driver? }
 */
export async function POST(req: Request) {
  const supa = createAdminClient();

  let body: { kind?: string; pairing_token?: string } = {};
  try {
    body = await req.json();
  } catch {
    // empty / invalid body handled below
  }

  const { data: companyRow } = await supa.from("company").select("name").limit(1).maybeSingle();
  const company = companyRow?.name ?? "Taxi company";

  // ── Passenger ──────────────────────────────────────────────────────────────
  if (body.kind === "passenger") {
    const { data: passenger, error: pErr } = await supa
      .from("passenger")
      .insert({ kind: "anonymous" })
      .select("id")
      .single();
    if (pErr) return NextResponse.json({ error: pErr.message }, { status: 500 });

    const token = newToken();
    const { error: dErr } = await supa
      .from("device")
      .insert({ kind: "passenger", passenger_id: passenger.id, token_hash: hashToken(token) });
    if (dErr) return NextResponse.json({ error: dErr.message }, { status: 500 });

    return NextResponse.json({ token, company });
  }

  // ── Driver ───────────────────────────────────────────────────────────────
  if (body.kind === "driver") {
    const code = body.pairing_token;
    if (!code) {
      return NextResponse.json({ error: "missing pairing_token" }, { status: 400 });
    }

    const { data: pc } = await supa
      .from("pairing_code")
      .select("id, taxi_id, driver_id")
      .eq("code", code)
      .is("used_at", null)
      .gt("expires_at", new Date().toISOString())
      .maybeSingle();

    if (!pc) {
      return NextResponse.json({ error: "invalid or expired pairing code" }, { status: 400 });
    }

    const token = newToken();
    const { data: device, error: dErr } = await supa
      .from("device")
      .insert({
        kind: "driver",
        driver_id: pc.driver_id,
        taxi_id: pc.taxi_id,
        token_hash: hashToken(token),
      })
      .select("id")
      .single();
    if (dErr) return NextResponse.json({ error: dErr.message }, { status: 500 });

    await supa
      .from("pairing_code")
      .update({ used_at: new Date().toISOString(), used_by_device: device.id })
      .eq("id", pc.id);

    return NextResponse.json({ token, company, taxi: pc.taxi_id, driver: pc.driver_id });
  }

  return NextResponse.json({ error: "unknown kind" }, { status: 400 });
}
